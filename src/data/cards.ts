export function buildAnnualDecks(side: Side): Record<1941 | 1942 | 1943 | 1944, Card[]> {
  const seeds = side === 'AXIS' ? AXIS_CARD_SEEDS : USSR_CARD_SEEDS;
  const result: Record<1941 | 1942 | 1943 | 1944, Card[]> = {
    1941: [],
    1942: [],
    1943: [],
    1944: [],
  };

  for (const seed of seeds) {
    for (let i = 1; i <= seed.qty; i++) {
      const { qty, ...rest } = seed;
      const card: Card = {
        ...rest,
        id: `${seed.templateId}_${i}`,
      } as Card;
      result[seed.year].push(card);
    }
  }

  return result;
}
